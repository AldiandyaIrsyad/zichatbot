"""Build Subset D-Hard — Adversarial RAM Ground Truth.

The natural Subset D (``build_subset_d.py``) samples questions round-robin
from Subset A, which were themselves pre-validated as clearly answerable and
hallucination-free — so real pipeline responses to them skew heavily toward
the ``supported`` label. That makes Subset D a weak test of RAM's actual
discriminative power (an "always predict supported" baseline would score
close to it).

This script builds a genuinely *harder* companion set using the SAME live
pipeline and the SAME 5-model panel majority-vote judgment as Subset D (no
label fabrication — only the input questions are chosen to be harder to
answer correctly). Five techniques:

    1. Reweighted Subset A sampling: exclude ``out-of-domain`` questions
       (they only produce IVM abstention, contributing zero sentence-level
       signal — that's Experiment 4's territory, not RAM's) and bias toward
       ``multi-hop`` > ``procedural`` > ``factual`` (synthesis/multi-step
       answers are more error-prone than single-paragraph lookups).
    2. Precise-detail-recall questions: generated from real KB document
       text, asking for an exact number/date/name/article — the classic
       hallucination trigger (LLMs paraphrase/approximate these).
    3. Cross-document synthesis questions: generated by combining excerpts
       from two different real KB documents, forcing genuine multi-hop
       retrieval that top-k retrieval may not fully surface.
    4. Boundary-query injection (reused from Subset C): a handful of
       ``near_miss_government`` / ``adjacent_legal`` queries — topically
       similar-sounding but not truly in-domain. If the IVM relevance gate
       lets one through, the pipeline is likely to answer with thin/absent
       grounding, a genuine source of ``not_supported`` sentences.
    5. Evaluative/rationale-eliciting questions: asking for a grounded fact
       PLUS its rationale/significance/impact. Formal legal/administrative
       documents state the *what* but rarely the *why*, which structurally
       invites a response combining a grounded fact with an ungrounded
       evaluative elaboration — precisely the pattern that defines
       ``partially_supported`` (e.g. "Salah satunya adalah penataan
       manajemen perubahan yang sangat penting" — the fact is grounded,
       "sangat penting" is not). Targets the ``partially_supported`` label
       specifically, which techniques 1-4 do not produce.

Output schema is identical to Subset D (question_id, question, full_response,
sentence_id, sentence_text, retrieved_context, label, verifier_note), so this
file can be used standalone with ``exp3_ram``
(``--dataset evals/data/subset_d_hard.csv``) or concatenated with the natural
Subset D for a combined evaluation. Question IDs are prefixed by source
(``qh-reweighted-``, ``qh-detail-``, ``qh-crossdoc-``, ``qh-boundary-``,
``qh-evaluative-``) for breakdown analysis.
"""

