DETAIL_SYSTEM_PROMPT = """\
You are a dataset generator for a hallucination-detection stress test about \
UPI internal legal/regulatory documents (JDIH). Given a document excerpt, \
generate ONE question that demands a single, PRECISE, easy-to-misremember \
detail from the text: an exact number, percentage, date, article/pasal \
number, or a specific person's name/title. Avoid vague or paraphrasable \
questions. Output a single JSON object with one field: "question" \
(Indonesian). Do not include markdown code fences.
"""

CROSSDOC_SYSTEM_PROMPT = """\
You are a dataset generator for a hallucination-detection stress test about \
UPI internal legal/regulatory documents (JDIH). You are given excerpts from \
TWO different documents. Generate ONE question in Indonesian that can only \
be fully and correctly answered by combining information from BOTH \
documents (e.g. comparing a rule in Document A against a related rule or \
person in Document B). Output a single JSON object with one field: \
"question". Do not include markdown code fences.
"""

EVALUATIVE_SYSTEM_PROMPT = """\
You are a dataset generator for a hallucination-detection stress test about \
UPI internal legal/regulatory documents (JDIH). Given a document excerpt, \
generate ONE question in Indonesian that asks for a specific grounded fact \
from the text AND ALSO asks for its rationale, significance, or impact \
(e.g. "berapa besar sanksinya dan mengapa ditetapkan sebesar itu?", "siapa \
yang bertanggung jawab dan mengapa perannya penting?", "apa isi ketentuan \
ini dan apa dampaknya bagi mahasiswa?"). Formal legal/administrative \
documents typically state the fact but not the rationale/significance, so \
this format is likely to elicit a response combining a correct fact with \
an unsupported evaluative elaboration. Output a single JSON object with \
one field: "question". Do not include markdown code fences.
"""


def sample_reweighted_subset_a(rows: List[Any], count: int) -> List[str]:
    """Sample Subset A questions biased toward harder-to-support categories.

    Excludes ``out-of-domain`` rows (they only trigger IVM abstention, not
    sentence-level RAM signal) and allocates roughly 50% multi-hop, 30%
    procedural, 20% factual — the categories most likely to require
    synthesis across multiple facts, which is more error-prone than a
    single-paragraph factual lookup.
    """
    by_category: Dict[str, List[str]] = {"multi-hop": [], "procedural": [], "factual": []}
    for r in rows:
        if r.category in by_category:
            by_category[r.category].append(r.question)

    quotas = {
        "multi-hop": int(count * 0.5),
        "procedural": int(count * 0.3),
        "factual": int(count * 0.2),
    }

    selected: List[str] = []
    leftovers: List[str] = []
    for cat, quota in quotas.items():
        pool = by_category[cat]
        selected.extend(pool[:quota])
        leftovers.extend(pool[quota:])

    if len(selected) < count:
        selected.extend(leftovers[: count - len(selected)])

    return selected[:count]


async def generate_detail_questions(
    generator: DatasetGenerator,
    api_url: str,
    docs: List[Dict[str, Any]],
    n: int,
) -> List[str]:
    """Generate precise-detail-recall questions from real KB document text."""
    questions: List[str] = []
    doc_cycle = list(docs)
    random.shuffle(doc_cycle)

    attempts = 0
    max_attempts = max(3 * n, 30)  # cap so a parse regression can't loop the whole corpus
    for doc in doc_cycle:
        if len(questions) >= n or attempts >= max_attempts:
            break
        doc_text = await fetch_document_text(api_url, doc.get("id", ""), doc.get("title", ""))
        if not doc_text:
            continue
        attempts += 1
        seed_prompt = f"Document excerpt:\n\n{doc_text[:3000]}\n\nGenerate 1 precise-detail-recall question."
        try:
            raw = await generator.generate_single(prompt=seed_prompt, system_prompt=DETAIL_SYSTEM_PROMPT)
        except Exception as e:
            logger.error("datagen.subset_d_hard.detail_generator_error", error=str(e), exc_info=True)
            continue
        obj = parse_json_object(raw)
        if obj and str(obj.get("question", "")).strip():
            questions.append(str(obj["question"]).strip())

    return questions[:n]


async def generate_evaluative_questions(
    generator: DatasetGenerator,
    api_url: str,
    docs: List[Dict[str, Any]],
    n: int,
) -> List[str]:
    """Generate rationale-eliciting questions from real KB document text.

    Asks for a grounded fact plus its rationale/significance/impact — a
    pattern formal legal documents rarely state explicitly, so it's likely
    to elicit responses combining a supported fact with an unsupported
    evaluative elaboration (targets the ``partially_supported`` label).
    """
    questions: List[str] = []
    doc_cycle = list(docs)
    random.shuffle(doc_cycle)

    attempts = 0
    max_attempts = max(3 * n, 30)
    for doc in doc_cycle:
        if len(questions) >= n or attempts >= max_attempts:
            break
        doc_text = await fetch_document_text(api_url, doc.get("id", ""), doc.get("title", ""))
        if not doc_text:
            continue
        attempts += 1
        seed_prompt = f"Document excerpt:\n\n{doc_text[:3000]}\n\nGenerate 1 evaluative/rationale-eliciting question."
        try:
            raw = await generator.generate_single(prompt=seed_prompt, system_prompt=EVALUATIVE_SYSTEM_PROMPT)
        except Exception as e:
            logger.error("datagen.subset_d_hard.evaluative_generator_error", error=str(e), exc_info=True)
            continue
        obj = parse_json_object(raw)
        if obj and str(obj.get("question", "")).strip():
            questions.append(str(obj["question"]).strip())

    return questions[:n]


async def generate_crossdoc_questions(
    generator: DatasetGenerator,
    api_url: str,
    docs: List[Dict[str, Any]],
    n: int,
) -> List[str]:
    """Generate cross-document synthesis questions from pairs of real KB documents."""
    questions: List[str] = []
    if len(docs) < 2:
        return questions

    pairs = list(docs)
    random.shuffle(pairs)
    pair_iter = [(pairs[i], pairs[i + 1]) for i in range(0, len(pairs) - 1, 2)]

    attempts = 0
    max_attempts = max(3 * n, 30)
    for doc_a, doc_b in pair_iter:
        if len(questions) >= n or attempts >= max_attempts:
            break
        text_a = await fetch_document_text(api_url, doc_a.get("id", ""), doc_a.get("title", ""))
        text_b = await fetch_document_text(api_url, doc_b.get("id", ""), doc_b.get("title", ""))
        if not text_a or not text_b:
            continue
        attempts += 1
        seed_prompt = (
            f"--- DOCUMENT A ---\n{text_a[:1500]}\n\n"
            f"--- DOCUMENT B ---\n{text_b[:1500]}\n\n"
            "Generate 1 cross-document synthesis question."
        )
        try:
            raw = await generator.generate_single(prompt=seed_prompt, system_prompt=CROSSDOC_SYSTEM_PROMPT)
        except Exception as e:
            logger.error("datagen.subset_d_hard.crossdoc_generator_error", error=str(e), exc_info=True)
            continue
        obj = parse_json_object(raw)
        if obj and str(obj.get("question", "")).strip():
            questions.append(str(obj["question"]).strip())

    return questions[:n]


def sample_boundary_queries(subset_c_rows: List[Any], n: int) -> List[str]:
    """Sample near-miss/adjacent boundary queries from Subset C."""
    pool = [r.query for r in subset_c_rows if r.subtype in ("near_miss_government", "adjacent_legal")]
    random.shuffle(pool)
    return pool[:n]


async def process_question(
    panel: EvaluatorPanel,
    api_url: str,
    question: str,
    question_id: str,
    blind_tracker: BlindInjectionTracker,
) -> Tuple[List[Dict[str, Any]], int, int]:
    """Run one question through the live pipeline and label its sentences.

    Returns (accepted rows, sentences accepted, sentences rejected).
    """
    accepted: List[Dict[str, Any]] = []
    n_accepted = 0
    n_rejected = 0

    try:
        session_id = await create_session(api_url)
    except Exception as e:
        logger.error("datagen.subset_d_hard.session_create_failed", error=str(e), exc_info=True)
        return accepted, n_accepted, n_rejected

    try:
        result = await run_pipeline(api_url, session_id, question)
    except Exception as e:
        logger.error("datagen.subset_d_hard.pipeline_error", error=str(e), exc_info=True)
        return accepted, n_accepted, n_rejected

    if not result or not result.get("response"):
        logger.warning("datagen.subset_d_hard.no_response", question_id=question_id)
        return accepted, n_accepted, n_rejected

    full_response = result["response"]
    retrieved_context = result.get("context", "")
    chunks = result.get("chunks", [])
    sentences = split_sentences(full_response)
    logger.info("datagen.subset_d_hard.decomposed", question_id=question_id, sentence_count=len(sentences))

    # Shares label_sentence with build_subset_d.py so both scripts get the
    # same fragment filter, chunk narrowing (cost + quality), and
    # accept/dispute/drop plurality-fallback logic.
    panel_session_id = f"subset-d-hard-{question_id}"
    for sent_idx, sentence in enumerate(sentences):
        row, status, unanimous = await label_sentence(
            panel=panel,
            question=question,
            question_id=question_id,
            full_response=full_response,
            sentence=sentence,
            sent_idx=sent_idx,
            retrieved_context=retrieved_context,
            chunks=chunks,
            session_id=panel_session_id,
        )

        if row is not None:
            accepted.append(row)
            n_accepted += 1
            if unanimous:
                blind_tracker.add_candidate({**row, "_panel_label": row["label"]})
            logger.info("datagen.subset_d_hard.sentence_labeled", sentence_id=sent_idx, label=row["label"], status=status)
        else:
            n_rejected += 1
            logger.info("datagen.subset_d_hard.sentence_skipped", sentence_id=sent_idx, status=status)

    return accepted, n_accepted, n_rejected


async def build_subset_d_hard(
    settings: DatasetGenSettings,
    api_url: str,
    subset_a_path: str,
    subset_c_path: Optional[str],
    output_path: str,
    count_reweighted: int,
    count_detail: int,
    count_crossdoc: int,
    count_boundary: int,
    count_evaluative: int,
) -> None:
    """Build Subset D-Hard (adversarial RAM ground truth) and save to CSV.

    Args:
        subset_c_path: Path to Subset C CSV, or None to skip boundary injection.
        count_reweighted: Number of reweighted Subset A questions to include.
        count_detail: Number of precise-detail questions to generate.
        count_crossdoc: Number of cross-document questions to generate.
        count_boundary: Number of boundary queries to inject.
        count_evaluative: Number of evaluative/rationale-eliciting questions to generate.
    """
    if not settings.openrouter_api_key:
        logger.error("datagen.subset_d_hard.missing_api_key")
        sys.exit(1)

    # 1. Reweighted Subset A sample
    subset_a_rows = load_subset_a(subset_a_path)
    reweighted = sample_reweighted_subset_a(subset_a_rows, count_reweighted)
    logger.info("datagen.subset_d_hard.reweighted_sampled", count=len(reweighted))

    generator = DatasetGenerator(settings)
    panel = EvaluatorPanel(settings)
    blind_tracker = BlindInjectionTracker()

    questions_by_source: List[Tuple[str, str]] = [(q, "reweighted") for q in reweighted]

    try:
        # 2, 3 & 5. Precise-detail, cross-document, and evaluative questions
        # all need real KB text
        if count_detail > 0 or count_crossdoc > 0 or count_evaluative > 0:
            logger.info("datagen.subset_d_hard.fetching_docs")
            docs = await fetch_kb_documents(api_url)
            if not docs:
                logger.warning("datagen.subset_d_hard.no_active_docs")
                docs = []

            if count_detail > 0 and docs:
                detail_qs = await generate_detail_questions(generator, api_url, docs, count_detail)
                logger.info("datagen.subset_d_hard.detail_generated", count=len(detail_qs))
                questions_by_source.extend((q, "detail") for q in detail_qs)

            if count_crossdoc > 0 and docs:
                crossdoc_qs = await generate_crossdoc_questions(generator, api_url, docs, count_crossdoc)
                logger.info("datagen.subset_d_hard.crossdoc_generated", count=len(crossdoc_qs))
                questions_by_source.extend((q, "crossdoc") for q in crossdoc_qs)

            if count_evaluative > 0 and docs:
                evaluative_qs = await generate_evaluative_questions(generator, api_url, docs, count_evaluative)
                logger.info("datagen.subset_d_hard.evaluative_generated", count=len(evaluative_qs))
                questions_by_source.extend((q, "evaluative") for q in evaluative_qs)

        # 4. Boundary query injection
        if count_boundary > 0 and subset_c_path:
            subset_c_rows = load_subset_c(subset_c_path)
            boundary_qs = sample_boundary_queries(subset_c_rows, count_boundary)
            logger.info("datagen.subset_d_hard.boundary_sampled", count=len(boundary_qs))
            questions_by_source.extend((q, "boundary") for q in boundary_qs)

        if not questions_by_source:
            logger.error("datagen.subset_d_hard.no_questions")
            sys.exit(1)

        # 5. Run every question through the live pipeline + panel labeling
        accepted_items: List[Dict[str, Any]] = []
        total_accepted = 0
        total_rejected = 0
        source_counters: Dict[str, int] = {}

        for question, source in questions_by_source:
            source_counters[source] = source_counters.get(source, 0) + 1
            question_id = f"qh-{source}-{source_counters[source]:03d}"
            logger.info(
                "datagen.subset_d_hard.processing",
                question_id=question_id,
                source=source,
                question=question[:60],
            )
            rows, n_acc, n_rej = await process_question(panel, api_url, question, question_id, blind_tracker)
            accepted_items.extend(rows)
            total_accepted += n_acc
            total_rejected += n_rej

    finally:
        await generator.aclose()
        await panel.aclose()

    # Write blind-injection sidecar
    blind_tracker.write_sidecar(
        output_path.replace(".csv", "_blind_injection.csv"),
        fieldnames=[
            "question_id", "question", "full_response", "sentence_id",
            "sentence_text", "retrieved_context", "label", "verifier_note",
        ],
    )

    # Write CSV
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)

    with output.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "question_id", "question", "full_response", "sentence_id",
                "sentence_text", "retrieved_context", "label", "verifier_note",
            ],
        )
        writer.writeheader()
        writer.writerows(accepted_items)

    write_provenance(
        output_path,
        subset="d_hard",
        settings=settings,
        row_count=len(accepted_items),
        extra={
            "source_subset_a": subset_a_path,
            "source_subset_c": subset_c_path,
            "questions_processed": len(questions_by_source),
            "by_hardening_source": dict(source_counters),
            "sentences_rejected": total_rejected,
            # See the note in build_subset_d — same regeneration sanity check.
            "label_distribution": Counter(r.get("label", "") for r in accepted_items),
        },
    )

    logger.info(
        "datagen.subset_d_hard.complete",
        questions_processed=len(questions_by_source),
        sentences_accepted=total_accepted,
        sentences_rejected=total_rejected,
        by_source=source_counters,
        output=output_path,
    )


def main() -> None:
    """Entry point for Subset D-Hard generation.

    DEPRECATED as a standalone builder. Question-hardening alone only hardens
    the *question*, which a well-grounded pipeline still answers faithfully —
    the result skews heavily ``supported`` with no ``partially_supported``.
    Subset D is built by ``build_subset_d.py``, which imports the question
    generators below for its natural backbone and adds a panel-verified
    counterfactual-perturbation core. This entry point is retained only so the
    generators remain importable; do not run it to produce a dataset.
    """
    print(
        "DEPRECATED: run `python -m evals._dataset_gen.build_subset_d` "
        "instead — the hard Subset D is now a single file (natural backbone + "
        "verified perturbation core). This script's generators are reused there.",
        file=sys.stderr,
    )
    parser = argparse.ArgumentParser(
        description="[DEPRECATED] Build Subset D-Hard — use build_subset_d instead."
    )
    parser.add_argument("--api-url", default="http://localhost:8000", help="Base URL of the running application")
    parser.add_argument("--subset-a", default="evals/data/subset_a.csv", help="Path to Subset A CSV")
    parser.add_argument("--subset-c", default="evals/data/subset_c.csv", help="Path to Subset C CSV (for boundary injection)")
    parser.add_argument("--output", default="evals/data/subset_d_hard.csv", help="Output CSV path")
    parser.add_argument("--count-reweighted", type=int, default=15, help="Reweighted Subset A questions to include")
    parser.add_argument("--count-detail", type=int, default=8, help="Precise-detail questions to generate")
    parser.add_argument("--count-crossdoc", type=int, default=7, help="Cross-document questions to generate")
    parser.add_argument("--count-boundary", type=int, default=5, help="Boundary queries to inject from Subset C")
    parser.add_argument("--count-evaluative", type=int, default=8, help="Evaluative/rationale-eliciting questions to generate")
    args = parser.parse_args()

    settings = get_dataset_gen_settings()
    asyncio.run(
        build_subset_d_hard(
            settings,
            args.api_url,
            args.subset_a,
            args.subset_c,
            args.output,
            args.count_reweighted,
            args.count_detail,
            args.count_crossdoc,
            args.count_boundary,
            args.count_evaluative,
        )
    )


if __name__ == "__main__":
    main()
